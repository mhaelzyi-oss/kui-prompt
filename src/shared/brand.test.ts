import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { describe, expect, it } from "vitest";
import { SPONSORS_URL, TIPS } from "./tips.js";
import { VERBS } from "./verbs.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");

describe("brand", () => {
  it("keeps gold, MIT, sponsors, twelve verbs, and no visible email", () => {
    const readme = readFileSync(join(root, "README.md"), "utf8");
    const css = readFileSync(join(root, "src/renderer/style.css"), "utf8");
    const app = readFileSync(join(root, "src/renderer/App.tsx"), "utf8");
    const terms = readFileSync(join(root, "TERMS.md"), "utf8");
    const icon = readFileSync(join(root, "branding/icon-prompt.svg"), "utf8");
    const pkg = readFileSync(join(root, "package.json"), "utf8");
    expect(css).toMatch(/#c9a227/i);
    expect(css).toMatch(/#f7f4ee/i);
    expect(css).toMatch(/#6b1414/i);
    expect(readme).toMatch(/Krypton Ultimate Inc II/);
    expect(readme).toMatch(/MIT/);
    expect(readme).toMatch(/https:\/\/github\.com\/sponsors\/mhaelzyi-oss/);
    expect(readme).toMatch(/\$5/);
    expect(readme).toMatch(/KUI Desk/);
    expect(app).toMatch(/Payment wall/);
    expect(app).toMatch(/SPONSORS_URL/);
    expect(app).toMatch(/KUI Desk/);
    expect(app).toMatch(/This PC/);
    expect(app).toMatch(/Phones/);
    expect(app).toMatch(/Leftovers/);
    expect(app).toMatch(/set aside/i);
    expect(app).toMatch(/delete forever/i);
    expect(app).toMatch(/save a copy/i);
    expect(app).toMatch(/hidden leftover/i);
    expect(app).not.toMatch(/\bresidual\b|classifier|PathGuard|\bFlow\b|visited/i);
    expect(TIPS.map((t) => t.amount)).toEqual([5, 9, 19]);
    expect(SPONSORS_URL).toBe("https://github.com/sponsors/mhaelzyi-oss");
    expect(app).not.toMatch(/Add to cart|Stripe|@gmail\.com|@outlook\.com/i);
    expect(readme).not.toMatch(/Add to cart|checkout|Stripe|@gmail\.com|@outlook\.com/i);
    expect(readme).toMatch(/no cart/i);
    expect(readme).toMatch(/no paid debugger SKU/i);
    expect(terms).toMatch(/You own this PC and the phones you plug in/i);
    expect(terms).not.toMatch(/only look/i);
    expect(terms).toMatch(/set aside/i);
    expect(terms).toMatch(/delete forever/i);
    expect(terms).toMatch(/save a copy/i);
    expect(terms).toMatch(/Root is not required/i);
    expect(terms).toMatch(/Nothing is uploaded/i);
    expect(terms).toMatch(/No warranty/i);
    expect(terms).toMatch(/MIT/);
    expect(terms).not.toMatch(/Add to cart|checkout|Stripe|@gmail\.com|@outlook\.com/i);
    expect(app).toMatch(/TERMS_KEY/);
    expect(app).toMatch(/kui-desk-terms/);
    expect(app).toMatch(/I understand/);
    expect(icon).toMatch(/#111821/);
    expect(icon).toMatch(/#d4af37/);
    expect(icon).toMatch(/#ffd966/);
    expect(icon).toMatch(/m35 27 0 42m0-21 27-21M35 48l29 21/);
    expect(icon).toMatch(/M62 78h20/);
    expect(icon).toMatch(/KUI Desk/);
    expect(pkg).toMatch(/"name": "kui-prompt"/);
    expect(pkg).toMatch(/KUI Desk/);
    expect(pkg).toMatch(/com\.kryptonultimateincII\.KUIDesk/);
    expect(pkg).toMatch(/"dist:win"/);
    expect(pkg).toMatch(/electron-builder/);
    expect(pkg).toMatch(/Krypton Ultimate Inc II/);
    for (const verb of VERBS) expect(readme).toContain(verb);
    expect(readme).toMatch(/## Not this[\s\S]*time travel[\s\S]*decompilers[\s\S]*protected processes/i);
  });
});
